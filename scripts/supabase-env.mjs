import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const localFile = join(root, ".env.supabase.local");

export function supabaseApiPort() {
  const config = readFileSync(join(root, "supabase/config.toml"), "utf8");
  const api = config.split(/^\[/m).find((section) => section.startsWith("api]"));
  return Number(api?.match(/^port = (\d+)/m)?.[1] ?? 54321);
}

export function readLocalSupabase() {
  if (!existsSync(localFile)) return null;
  return Object.fromEntries(
    readFileSync(localFile, "utf8")
      .split("\n")
      .filter((line) => line && !line.startsWith("#") && line.includes("="))
      .map((line) => [line.slice(0, line.indexOf("=")), line.slice(line.indexOf("=") + 1)]),
  );
}

export const SUPABASE_CLI_VERSION = "2.90.0";

export function supabaseBin() {
  const candidates = [process.env.SUPABASE_BIN, "supabase", `${process.env.HOME}/.local/bin/supabase`, "/opt/homebrew/bin/supabase"];
  for (const candidate of candidates.filter(Boolean)) {
    try {
      const version = execFileSync(candidate, ["--version"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
      return { bin: candidate, version };
    } catch {
      // try the next location
    }
  }
  return null;
}

export function requireSupabaseBin() {
  const cli = supabaseBin();
  if (!cli) {
    throw new Error(`Supabase CLI ${SUPABASE_CLI_VERSION} not found. Set SUPABASE_BIN or install it (see docs/LOCAL_DEVELOPMENT.md).`);
  }
  if (cli.version !== SUPABASE_CLI_VERSION) {
    throw new Error(`Supabase CLI ${cli.version} found at ${cli.bin}; this repo is pinned to ${SUPABASE_CLI_VERSION}.`);
  }
  return cli.bin;
}

export function captureLocalSupabase() {
  const output = execFileSync(requireSupabaseBin(), ["status", "--workdir", root, "-o", "env"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  const status = Object.fromEntries(
    output
      .split("\n")
      .filter((line) => line.includes("="))
      .map((line) => {
        const index = line.indexOf("=");
        return [line.slice(0, index), line.slice(index + 1).replace(/^"|"$/g, "")];
      }),
  );
  if (!status.PUBLISHABLE_KEY || !status.SECRET_KEY) {
    throw new Error("supabase status did not report local keys. Run make supabase-start first.");
  }
  const url = `http://127.0.0.1:${supabaseApiPort()}`;
  const values = {
    SUPABASE_URL: url,
    SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY,
    SUPABASE_SECRET_KEY: status.SECRET_KEY,
    SUPABASE_JWT_ISSUER: `${url}/auth/v1`,
    SUPABASE_JWT_AUDIENCE: "authenticated",
    SUPABASE_JWKS_URL: `${url}/auth/v1/.well-known/jwks.json`,
  };
  const preserved = Object.entries(readLocalSupabase() ?? {}).filter(([key]) => !(key in values));
  const body = [
    "# Generated by scripts/supabase-env.mjs from the local Supabase CLI stack.",
    "# Local development only. Do not copy these values to staging or production.",
    ...[...Object.entries(values), ...preserved].map(([key, value]) => `${key}=${value}`),
    "",
  ].join("\n");
  writeFileSync(localFile, body, { mode: 0o600 });
  writeFileSync(
    join(root, "ios/Config/Local.xcconfig"),
    `// Generated by scripts/supabase-env.mjs for simulator Debug builds. Public client values only.\nSUPABASE_PUBLISHABLE_KEY = ${values.SUPABASE_PUBLISHABLE_KEY}\n`,
  );
  return values;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const values = captureLocalSupabase();
  console.log(`wrote .env.supabase.local (${Object.keys(values).join(", ")}; values hidden)`);
}
